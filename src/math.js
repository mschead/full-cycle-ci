function add(a, b) {
  return a + b;
}

function subtract(a, b) {
  return a - b;
}

function multiply(a, b) {
  return a * b;
}

function divide(a, c) {
  return a / c;
}

function square(a) {
  return a * a;
}

function modulo(a, b) {
  return a % b;
}

module.exports = { add, subtract, multiply, divide, square, modulo };
